const { test, expect } = require('@playwright/test');
const path = require('node:path');

test('character sheet review preserves originals and prepares a portrait', async ({ page }, testInfo) => {
  test.setTimeout(120000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/accounts/login/');
  await page.locator('[name="login"]').fill(`character-${testInfo.project.name}@example.com`);
  await page.locator('[name="password"]').fill('Portrait-test-2026!');
  await page.getByRole('button', { name: 'Masuk', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Akun saya', exact: true })).toBeVisible();
  const catalog = await (await page.request.get('/api/v1/templates')).json();
  const template = catalog.items.find(item => item.slug === 'lebaran');
  await page.goto(`/#/studio/${template.id}`);
  for (const [index, name] of ['left', 'right'].entries()) {
    await page.getByRole('button', { name: `Tambahkan foto wajah ${index + 1}`, exact: true }).click();
    await page.getByLabel('Foto JPEG atau PNG').setInputFiles(path.join(__dirname, `generated/${name}.jpg`));
    await page.getByRole('checkbox').check();
    await page.getByRole('button', { name: 'Cek dan pasang foto' }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
  }
  await expect(page.locator('.character-reference')).toHaveCount(2);
  await page.locator('.character-references summary').click();
  await page.getByRole('button', { name: 'Lihat referensi wajah 1', exact: true }).click();
  await expect(page.getByRole('dialog').getByText('Foto asli', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Buat referensi multi-sudut', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'Cek kemiripan wajah 1', exact: true }).click({ timeout: 30000 });
  await page.getByRole('button', { name: 'Belum mirip', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button', { name: 'Lihat referensi wajah 1', exact: true }).click();
  await page.getByRole('button', { name: 'Buat referensi multi-sudut', exact: true }).click();
  await page.getByRole('button', { name: 'Cek kemiripan wajah 1', exact: true }).click({ timeout: 30000 });
  await expect(page.getByText(/Sudut lain merupakan perkiraan AI/)).toBeVisible();
  await page.getByRole('button', { name: 'Sudah mirip', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.locator('.character-reference').first()).toContainText('Multi-sudut disetujui');
  await page.reload();
  await expect(page.locator('.character-reference').first()).toContainText('Multi-sudut disetujui');
  await page.getByRole('button', { name: 'Ganti template', exact: true }).click();
  await page.getByRole('button', { name: 'Kebersamaan keluarga', exact: true }).click();
  await page.getByRole('button', { name: `Pilih ${catalog.items.find(item => item.slug === 'home').name}`, exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Penempatan 2 wajah akan dikosongkan.');
  await page.keyboard.press('Escape');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('character-studio.png'), fullPage: true });
  await page.getByRole('button', { name: 'Buat foto keluarga' }).click();
  await expect(page.getByRole('heading', { name: 'Yuk, cek hasil fotomu', exact: true })).toBeVisible({ timeout: 30000 });
  await page.getByRole('button', { name: 'Bandingkan wajah 1', exact: true }).click();
  await expect(page.getByRole('dialog').getByText('Wajah di hasil', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Belum mirip', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Wajah 1 · versi 1');
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.locator('.reference-grid figure').first()).toContainText('Perlu koreksi');
  await page.getByRole('button', { name: 'Bandingkan wajah 2', exact: true }).click();
  await page.getByRole('button', { name: 'Orang tidak sesuai', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Wajah 2 · versi 1');
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.locator('.reference-grid figure').nth(1)).toContainText('Perlu koreksi');
  expect(errors).toEqual([]);
});
